USE ecommerce_db;

-- BASIC LEVEL

-- 1. Write a query to retrieve all customer records.
SELECT * FROM customers;

-- 2. Display the customer names, email addresses, and cities of all customers.
SELECT customer_name, email, city
FROM customers;

-- 3. Find all customers who belong to Chennai.
SELECT *
FROM customers
WHERE city = 'Chennai';

-- 4. Retrieve all products priced above ₹5,000.
SELECT *
FROM products
WHERE price > 5000;

-- 5. Find products priced between ₹1,000 and ₹5,000.
SELECT *
FROM products
WHERE price BETWEEN 1000 AND 5000;

-- 6. Display all customers from Chennai or Bangalore.
SELECT *
FROM customers
WHERE city IN ('Chennai', 'Bangalore');

-- 7. Find all products whose names contain the word 'Phone'.
SELECT *
FROM products
WHERE product_name LIKE '%Phone%';

-- 8. Retrieve all orders with status = 'Pending'.
SELECT *
FROM orders
WHERE status = 'Pending';

-- 9. Find all payments with status = 'Failed'.
SELECT *
FROM payments
WHERE payment_status = 'Failed';

-- 10. Display the top 10 most expensive products.
SELECT *
FROM products
ORDER BY price DESC
LIMIT 10;

-- 11. Retrieve all customers sorted alphabetically by name.
SELECT *
FROM customers
ORDER BY customer_name ASC;

-- 12. Find the minimum, maximum, and average product price.
SELECT MIN(price) AS minimum_price,
       MAX(price) AS maximum_price,
       AVG(price) AS average_price
FROM products;

-- 13. Find the total number of customers registered in the database.
SELECT COUNT(*) AS total_customers
FROM customers;

-- 14. Calculate the total order amount from all orders.
SELECT SUM(total_amount) AS total_order_amount
FROM orders;

-- 15. Find the total number of payments grouped by payment status.
SELECT payment_status, COUNT(*) AS total_payments
FROM payments
GROUP BY payment_status;


-- INTERMEDIATE LEVEL

-- 16. Find the total number of orders placed by each customer.
SELECT c.customer_id, c.customer_name, COUNT(o.order_id) AS total_orders
FROM customers c
LEFT JOIN orders o ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.customer_name;

-- 17. Retrieve customers who have placed more than one order.
SELECT c.customer_id, c.customer_name, COUNT(o.order_id) AS total_orders
FROM customers c
JOIN orders o ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.customer_name
HAVING COUNT(o.order_id) > 1;

-- 18. Find the total purchase amount for each customer.
SELECT c.customer_id, c.customer_name,
       COALESCE(SUM(o.total_amount), 0) AS total_purchase_amount
FROM customers c
LEFT JOIN orders o ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.customer_name;

-- 19. Calculate the average product price for each category.
SELECT cat.category_id, cat.category_name, AVG(p.price) AS average_price
FROM categories cat
JOIN products p ON cat.category_id = p.category_id
GROUP BY cat.category_id, cat.category_name;

-- 20. Find payment methods used more than 10 times.
SELECT payment_method, COUNT(*) AS usage_count
FROM payments
GROUP BY payment_method
HAVING COUNT(*) > 10;

-- 21. Display customer names alongside their order IDs and order amounts.
SELECT c.customer_name, o.order_id, o.total_amount
FROM customers c
JOIN orders o ON c.customer_id = o.customer_id;

-- 22. Retrieve product names, category names, and product prices.
SELECT p.product_name, cat.category_name, p.price
FROM products p
JOIN categories cat ON p.category_id = cat.category_id;

-- 23. Display each order with its payment method and payment status.
SELECT o.order_id, o.total_amount, p.payment_method, p.payment_status
FROM orders o
LEFT JOIN payments p ON o.order_id = p.order_id;

-- 24. Retrieve order IDs, product names, quantities, and unit prices for all order items.
SELECT oi.order_id, p.product_name, oi.quantity, oi.unit_price
FROM order_items oi
JOIN products p ON oi.product_id = p.product_id;

-- 25. Find products that do not have a matching inventory record.
SELECT p.product_id, p.product_name
FROM products p
LEFT JOIN inventory i ON p.product_id = i.product_id
WHERE i.product_id IS NULL;

-- 26. Retrieve products priced above the overall average product price.
SELECT *
FROM products
WHERE price > (SELECT AVG(price) FROM products);

-- 27. Find the most expensive product or products in the database.
SELECT *
FROM products
WHERE price = (SELECT MAX(price) FROM products);

-- 28. Find customers whose total order amount exceeds ₹50,000.
SELECT c.customer_id, c.customer_name, SUM(o.total_amount) AS total_order_amount
FROM customers c
JOIN orders o ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.customer_name
HAVING SUM(o.total_amount) > 50000;

-- 29. Use a CTE to calculate the total sales generated by each customer.
WITH CustomerSales AS (
    SELECT c.customer_id, c.customer_name,
           COALESCE(SUM(o.total_amount), 0) AS total_sales
    FROM customers c
    LEFT JOIN orders o ON c.customer_id = o.customer_id
    GROUP BY c.customer_id, c.customer_name
)
SELECT *
FROM CustomerSales
ORDER BY total_sales DESC;

-- 30. Find the three highest-value orders for each customer using a window function.
WITH RankedOrders AS (
    SELECT o.*,
           ROW_NUMBER() OVER (
               PARTITION BY customer_id
               ORDER BY total_amount DESC
           ) AS order_rank
    FROM orders o
)
SELECT *
FROM RankedOrders
WHERE order_rank <= 3;


-- ADVANCED LEVEL

-- 31. Find the top five customers who generated the highest total sales.
SELECT c.customer_id, c.customer_name, SUM(o.total_amount) AS total_sales
FROM customers c
JOIN orders o ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.customer_name
ORDER BY total_sales DESC
LIMIT 5;

-- 32. Retrieve customers who purchased products from multiple categories.
SELECT c.customer_id, c.customer_name,
       COUNT(DISTINCT p.category_id) AS categories_purchased
FROM customers c
JOIN orders o ON c.customer_id = o.customer_id
JOIN order_items oi ON o.order_id = oi.order_id
JOIN products p ON oi.product_id = p.product_id
GROUP BY c.customer_id, c.customer_name
HAVING COUNT(DISTINCT p.category_id) > 1;

-- 33. Find the category generating the maximum revenue.
WITH CategoryRevenue AS (
    SELECT cat.category_id, cat.category_name,
           SUM(oi.quantity * oi.unit_price) AS revenue
    FROM categories cat
    JOIN products p ON cat.category_id = p.category_id
    JOIN order_items oi ON p.product_id = oi.product_id
    GROUP BY cat.category_id, cat.category_name
)
SELECT *
FROM CategoryRevenue
WHERE revenue = (SELECT MAX(revenue) FROM CategoryRevenue);

-- 34. Display products that have been ordered more than 20 times.
SELECT p.product_id, p.product_name,
       SUM(oi.quantity) AS times_ordered
FROM products p
JOIN order_items oi ON p.product_id = oi.product_id
GROUP BY p.product_id, p.product_name
HAVING SUM(oi.quantity) > 20;

-- 35. Find the most frequently ordered product in the database.
WITH ProductOrderCounts AS (
    SELECT p.product_id, p.product_name,
           SUM(oi.quantity) AS total_quantity_ordered
    FROM products p
    JOIN order_items oi ON p.product_id = oi.product_id
    GROUP BY p.product_id, p.product_name
)
SELECT *
FROM ProductOrderCounts
WHERE total_quantity_ordered = (
    SELECT MAX(total_quantity_ordered)
    FROM ProductOrderCounts
);

-- 36. Retrieve products whose available inventory is below their reorder level.
SELECT p.product_id, p.product_name,
       i.quantity_available, i.reorder_level
FROM products p
JOIN inventory i ON p.product_id = i.product_id
WHERE i.quantity_available < i.reorder_level;

-- 37. Find customers who have never placed an order.
SELECT c.*
FROM customers c
LEFT JOIN orders o ON c.customer_id = o.customer_id
WHERE o.order_id IS NULL;

-- 38. Retrieve duplicate customer records based on customer name and email.
SELECT customer_name, email, COUNT(*) AS duplicate_count
FROM customers
GROUP BY customer_name, email
HAVING COUNT(*) > 1;

-- 39. Calculate the percentage contribution of each customer to total sales.
WITH CustomerSales AS (
    SELECT c.customer_id, c.customer_name,
           COALESCE(SUM(o.total_amount), 0) AS total_sales
    FROM customers c
    LEFT JOIN orders o ON c.customer_id = o.customer_id
    GROUP BY c.customer_id, c.customer_name
)
SELECT customer_id, customer_name, total_sales,
       ROUND(100.0 * total_sales / NULLIF(SUM(total_sales) OVER (), 0), 2)
           AS sales_percentage
FROM CustomerSales
ORDER BY sales_percentage DESC;

-- 40. Calculate the percentage contribution of each product category to total revenue.
WITH CategoryRevenue AS (
    SELECT cat.category_id, cat.category_name,
           COALESCE(SUM(oi.quantity * oi.unit_price), 0) AS revenue
    FROM categories cat
    LEFT JOIN products p ON cat.category_id = p.category_id
    LEFT JOIN order_items oi ON p.product_id = oi.product_id
    GROUP BY cat.category_id, cat.category_name
)
SELECT category_id, category_name, revenue,
       ROUND(100.0 * revenue / NULLIF(SUM(revenue) OVER (), 0), 2)
           AS revenue_percentage
FROM CategoryRevenue
ORDER BY revenue_percentage DESC;

-- 41. Find the monthly revenue generated by the e-commerce store.
