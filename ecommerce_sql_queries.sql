-- 47. Find the products that contribute to the highest percentage of total revenue.
WITH ProductRevenue AS (
    SELECT p.product_id, p.product_name,
           SUM(oi.quantity * oi.unit_price) AS revenue
    FROM products p
    JOIN order_items oi ON p.product_id = oi.product_id
    GROUP BY p.product_id, p.product_name
),
RevenueShare AS (
    SELECT product_id, product_name, revenue,
           100.0 * revenue / NULLIF(SUM(revenue) OVER (), 0) AS revenue_percentage
    FROM ProductRevenue
)
SELECT *
FROM RevenueShare
WHERE revenue_percentage = (SELECT MAX(revenue_percentage) FROM RevenueShare);

-- 48. Rank products within each category based on price using a window function.
SELECT p.product_id, p.product_name, p.category_id, p.price,
       RANK() OVER (
           PARTITION BY p.category_id
           ORDER BY p.price DESC
       ) AS price_rank
FROM products p;

-- 49. Calculate the running total of revenue by order date.
SELECT order_id, order_date, total_amount,
       SUM(total_amount) OVER (
           ORDER BY order_date, order_id
           ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
       ) AS running_revenue
FROM orders
ORDER BY order_date, order_id;

-- 50. Display customer performance rankings based on total spending,
-- number of orders, and average order value.
WITH CustomerPerformance AS (
    SELECT c.customer_id, c.customer_name,
           COALESCE(SUM(o.total_amount), 0) AS total_spending,
           COUNT(o.order_id) AS number_of_orders,
           AVG(o.total_amount) AS average_order_value
    FROM customers c
    LEFT JOIN orders o ON c.customer_id = o.customer_id
    GROUP BY c.customer_id, c.customer_name
)
SELECT customer_id, customer_name, total_spending, number_of_orders,
       average_order_value,
       RANK() OVER (ORDER BY total_spending DESC) AS spending_rank,
       RANK() OVER (ORDER BY number_of_orders DESC) AS order_count_rank,
       RANK() OVER (ORDER BY average_order_value DESC) AS average_value_rank
FROM CustomerPerformance;
